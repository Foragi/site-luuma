const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const output = path.join(root, "dist");
const outputMarker = path.join(output, ".luuma-static-build");
const htmlDirectory = path.join(root, "pages");
const htmlFiles = fs
  .readdirSync(htmlDirectory)
  .filter((file) => file.toLowerCase().endsWith(".html"))
  .map((file) => path.join(htmlDirectory, file));
const filesToCopy = new Set(htmlFiles);

function isExternalUrl(value) {
  return /^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(value);
}

function resolveLocalTarget(value, sourceFile) {
  if (isExternalUrl(value)) return null;

  const [pathAndQuery, fragment] = value.split("#", 2);
  const pathname = (pathAndQuery || "").split("?", 1)[0];
  const target = pathname
    ? path.resolve(path.dirname(sourceFile), decodeURIComponent(pathname))
    : sourceFile;

  if (target !== root && !target.startsWith(`${root}${path.sep}`)) {
    throw new Error(`Referência local sai do projeto: ${value} (${sourceFile})`);
  }

  if (!fs.existsSync(target) || !fs.statSync(target).isFile()) {
    throw new Error(`Arquivo local não encontrado: ${value} (${sourceFile})`);
  }

  if (fragment && path.extname(target).toLowerCase() === ".html") {
    const targetHtml = fs.readFileSync(target, "utf8");
    const escapedFragment = decodeURIComponent(fragment).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    if (!new RegExp(`\\bid=["']${escapedFragment}["']`).test(targetHtml)) {
      throw new Error(`Âncora #${fragment} não encontrada em ${path.relative(root, target)}`);
    }
  }

  filesToCopy.add(target);
  return target;
}

for (const htmlFile of htmlFiles) {
  const html = fs.readFileSync(htmlFile, "utf8");
  for (const match of html.matchAll(/(?:href|src|poster)=["']([^"']+)["']/gi)) {
    resolveLocalTarget(match[1], htmlFile);
  }
  for (const match of html.matchAll(/\bsrcset=["']([^"']+)["']/gi)) {
    for (const candidate of match[1].split(",")) {
      const source = candidate.trim().split(/\s+/, 1)[0];
      if (source) resolveLocalTarget(source, htmlFile);
    }
  }
}

for (const cssFile of [...filesToCopy].filter((file) => file.endsWith(".css"))) {
  const css = fs.readFileSync(cssFile, "utf8");
  for (const match of css.matchAll(/url\(["']?([^"')]+)["']?\)/gi)) {
    resolveLocalTarget(match[1].trim(), cssFile);
  }
}

for (const dependency of ["gsap", "lenis"]) {
  const dependencyPath = path.join(root, "node_modules", dependency);
  if (!fs.existsSync(dependencyPath)) {
    throw new Error(`Dependência necessária não encontrada: ${dependency}`);
  }
}

if (fs.existsSync(output)) {
  const outputIsEmpty = fs.readdirSync(output).length === 0;
  const isVercelBuild =
    process.env.VERCEL === "1" || Boolean(process.env.VERCEL_ENV) || Boolean(process.env.VERCEL_URL);

  if (!fs.existsSync(outputMarker) && !outputIsEmpty && !isVercelBuild) {
    throw new Error("A pasta dist contém arquivos sem o marcador deste build; ela foi preservada.");
  }

  // Vercel's configured output directory belongs to this build and may already exist.
  fs.rmSync(output, { recursive: true, force: true });
}

fs.mkdirSync(output, { recursive: true });
for (const sourceFile of filesToCopy) {
  const destinationFile = path.join(output, path.relative(root, sourceFile));
  fs.mkdirSync(path.dirname(destinationFile), { recursive: true });
  fs.copyFileSync(sourceFile, destinationFile);
}

for (const dependency of ["gsap", "lenis"]) {
  fs.cpSync(
    path.join(root, "node_modules", dependency),
    path.join(output, "node_modules", dependency),
    { recursive: true },
  );
}

fs.writeFileSync(
  path.join(output, "index.html"),
  '<!doctype html><html lang="pt-BR"><meta charset="utf-8"><meta http-equiv="refresh" content="0;url=pages/index.html"><title>Luuma Restaurante e Choperia</title><body><a href="pages/index.html">Abrir o site</a></body></html>\n',
  "utf8",
);
fs.writeFileSync(outputMarker, "Generated by npm run build.\n", "utf8");

console.log(`Build estático concluído: ${path.relative(root, output)}`);
console.log(`${htmlFiles.length} páginas HTML e seus arquivos locais foram reunidos para publicação.`);
